import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const root = join(import.meta.dir, '..')

/**
 * Concatenates `styles/*.css` in file-name order into one stylesheet. `00-tokens.css` comes first.
 */
export async function buildCss(): Promise<string> {
  const directory = join(root, 'styles')
  const files = (await readdir(directory)).filter((file) => file.endsWith('.css')).sort()
  const parts = await Promise.all(
    files.map(async (file) => `/* ${file} */\n${(await readFile(join(directory, file), 'utf8')).trim()}\n`)
  )
  return `/* Generated by scripts/build-css.ts from styles/*.css. Do not edit. */\n\n${parts.join('\n')}`
}

if (import.meta.main) {
  const css = await buildCss()
  await writeFile(join(root, 'src', 'styles.css'), css, 'utf8')
  console.log(`Wrote src/styles.css (${css.length} bytes)`)
}