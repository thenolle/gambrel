import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { isAbsolute, join, relative, resolve, sep } from 'node:path'
import { CompilerError } from './errors.ts'
import { discoverRoutes } from './discover.ts'
import type { RouteSource, RouteTable } from './table.ts'

export type GeneratedFileName = 'routes.ts' | 'manifest.client.ts' | 'manifest.server.ts'
export type GeneratedModules = Readonly<Record<GeneratedFileName, string>>

const HEADER = '// Generated by @gambrel/compiler. Do not edit.'

function quote(value: string): string {
  const escaped = JSON.stringify(value).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'")
  return `'${escaped}'`
}

function importSpecifier(fromDir: string, target: string): string {
  const path = relative(fromDir, target)
  if (isAbsolute(path)) throw new CompilerError(`Cannot import '${target}' from '${fromDir}': the paths must be on the same drive`)
  const posix = path.split(sep).join('/')
  return posix.startsWith('../') ? posix : `./${posix}`
}

function routesModule(table: RouteTable): string {
  const entries = table.routes.map((route) => `  { id: ${quote(route.id)}, pattern: ${quote(route.pattern)}, layouts: [${route.layouts.map(quote).join(', ')}] }`)
  return [
    HEADER,
    '',
    "import type { RouteRecord } from '@gambrel/router'",
    '',
    'export const routes: readonly RouteRecord[] = [',
    entries.join(',\n'),
    ']',
    ''
  ].join('\n')
}

function componentLines(table: RouteTable, outDir: string): { readonly names: ReadonlyMap<RouteSource, string>; readonly imports: string[]; readonly entries: string[] } {
  const names = new Map<RouteSource, string>()
  const imports: string[] = []
  const entries: string[] = []
  table.sources.forEach((source, index) => {
    const name = `${source.kind}_${index}`
    names.set(source, name)
    const specifier = importSpecifier(outDir, join(table.routesDir, source.file))
    imports.push(`import ${name} from ${quote(specifier)}`)
    entries.push(`  [${quote(source.id)}, ${name}]`)
  })
  return { names, imports, entries }
}

function clientModule(table: RouteTable, outDir: string): string {
  const { imports, entries } = componentLines(table, outDir)
  return [
    HEADER,
    '',
    "import type { AnyRouteComponent } from '@gambrel/router'",
    ...imports,
    '',
    "export { routes } from './routes.ts'",
    '',
    'export const components: ReadonlyMap<string, AnyRouteComponent> = new Map<string, AnyRouteComponent>([',
    entries.join(',\n'),
    '])',
    ''
  ].join('\n')
}

function serverModule(table: RouteTable, outDir: string): string {
  const { imports, entries } = componentLines(table, outDir)
  const hookImports: string[] = []
  const hookEntries: string[] = []
  table.sources.forEach((source, index) => {
    if (source.serverFile === undefined) return
    const name = `hooks_${index}`
    const specifier = importSpecifier(outDir, join(table.routesDir, source.serverFile))
    hookImports.push(`import * as ${name} from ${quote(specifier)}`)
    hookEntries.push(`  [${quote(source.id)}, hooksFromModule(${quote(source.id)}, ${name})]`)
  })
  const hooks = hookEntries.length === 0 ? ['export const hooks: ReadonlyMap<string, EntryHooks<never>> = new Map<string, EntryHooks<never>>()'] : ['export const hooks: ReadonlyMap<string, EntryHooks<never>> = new Map<string, EntryHooks<never>>([', hookEntries.join(',\n'), '])']
  return [
    HEADER,
    '',
    "import { hooksFromModule, type AnyRouteComponent, type EntryHooks } from '@gambrel/router'",
    ...imports,
    ...hookImports,
    '',
    "export { routes } from './routes.ts'",
    '',
    'export const components: ReadonlyMap<string, AnyRouteComponent> = new Map<string, AnyRouteComponent>([',
    entries.join(',\n'),
    '])',
    '',
    ...hooks,
    ''
  ].join('\n')
}

/**
 * Renders the generated modules as strings. Pure and deterministic: the same table and
 * output directory always give the same text. Import paths are relative to `outDir`.
 */
export function generateModules(table: RouteTable, outDir: string): GeneratedModules {
  return {
    'routes.ts': routesModule(table),
    'manifest.client.ts': clientModule(table, outDir),
    'manifest.server.ts': serverModule(table, outDir)
  }
}

async function readIfExists(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, 'utf8')
  } catch (error) {
    if (typeof error === 'object' && error !== null && 'code' in error && error.code === 'ENOENT') return undefined
    throw error
  }
}

/**
 * Writes the modules into `outDir`, skipping files whose content is unchanged.
 * Returns the names of the files that were written, sorted.
 */
export async function writeModules(modules: GeneratedModules, outDir: string): Promise<readonly GeneratedFileName[]> {
  await mkdir(outDir, { recursive: true })
  const written: GeneratedFileName[] = []
  const names = (Object.keys(modules) as GeneratedFileName[]).sort()
  for (const name of names) {
    const path = join(outDir, name)
    if ((await readIfExists(path)) === modules[name]) continue
    await writeFile(path, modules[name], 'utf8')
    written.push(name)
  }
  return written
}

export interface GenerateRoutesOptions {
  readonly root: string
  /**
   * Routes directory relative to `root`. Defaults to `src/routes`.
   */
  readonly routesDir?: string | undefined
  /**
   * Output directory relative to `root`. Defaults to `.gambrel`.
   */
  readonly outDir?: string | undefined
}

export interface GenerateRoutesResult {
  readonly table: RouteTable
  readonly outDir: string
  readonly written: readonly GeneratedFileName[]
}

/**
 * Discovers the routes and writes the generated modules.
 */
export async function generateRoutes(options: GenerateRoutesOptions): Promise<GenerateRoutesResult> {
  const root = resolve(options.root)
  const routesDir = resolve(root, options.routesDir ?? 'src/routes')
  const outDir = resolve(root, options.outDir ?? '.gambrel')
  const table = await discoverRoutes(routesDir)
  const written = await writeModules(generateModules(table, outDir), outDir)
  return { table, outDir, written }
}